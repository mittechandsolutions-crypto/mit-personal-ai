import "server-only";
import { mkdirSync } from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { neon } from "@neondatabase/serverless";

const sql = process.env.DATABASE_URL ? neon(process.env.DATABASE_URL) : null;

const globalForDatabase = globalThis as typeof globalThis & {
  mitDatabase?: DatabaseSync;
  mitSchemaReady?: Promise<void>;
};

const db = sql ? null : globalForDatabase.mitDatabase ?? createLocalDatabase();

if (db && process.env.NODE_ENV !== "production") globalForDatabase.mitDatabase = db;

function createLocalDatabase() {
  const databaseDirectory = path.join(process.cwd(), "data");
  const databasePath = path.join(databaseDirectory, "mit.sqlite");
  mkdirSync(databaseDirectory, { recursive: true });
  const database = new DatabaseSync(databasePath);
  database.exec("PRAGMA busy_timeout = 5000; PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;");
  database.exec(`
    CREATE TABLE IF NOT EXISTS conversations (
      id TEXT PRIMARY KEY,
      owner_id TEXT NOT NULL DEFAULT 'local',
      title TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS messages (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
      role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
      content TEXT NOT NULL,
      agent TEXT,
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS messages_conversation_id_idx ON messages(conversation_id, id);
  `);
  const columns = database.prepare("PRAGMA table_info(conversations)").all();
  if (!columns.some((column) => column.name === "owner_id")) {
    try {
      database.exec("ALTER TABLE conversations ADD COLUMN owner_id TEXT NOT NULL DEFAULT 'local'");
    } catch (error) {
      if (!(error instanceof Error) || !error.message.includes("duplicate column name: owner_id")) throw error;
    }
  }
  database.exec("CREATE INDEX IF NOT EXISTS conversations_owner_id_idx ON conversations(owner_id, updated_at)");
  return database;
}

function localDatabase() {
  if (!db) throw new Error("The local database is not configured.");
  return db;
}

async function initializeRemoteDatabase() {
  if (!sql) return;
  globalForDatabase.mitSchemaReady ??= (async () => {
    await sql`CREATE TABLE IF NOT EXISTS conversations (
      id TEXT PRIMARY KEY,
      owner_id TEXT NOT NULL DEFAULT 'local',
      title TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    )`;
    await sql`ALTER TABLE conversations ADD COLUMN IF NOT EXISTS owner_id TEXT NOT NULL DEFAULT 'local'`;
    await sql`CREATE TABLE IF NOT EXISTS messages (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
      role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
      content TEXT NOT NULL,
      agent TEXT,
      created_at TIMESTAMPTZ NOT NULL
    )`;
    await sql`CREATE INDEX IF NOT EXISTS messages_conversation_id_idx ON messages(conversation_id, id)`;
    await sql`CREATE INDEX IF NOT EXISTS conversations_owner_id_idx ON conversations(owner_id, updated_at)`;
  })();
  await globalForDatabase.mitSchemaReady;
}

function isoDate(value: unknown) {
  return value instanceof Date ? value.toISOString() : String(value);
}

export type ConversationSummary = {
  id: string;
  title: string;
  createdAt: string;
  updatedAt: string;
  messageCount: number;
};

export type ConversationMessage = {
  id: number;
  role: "user" | "assistant";
  content: string;
  agent: string | null;
  createdAt: string;
};

export async function listConversations(ownerId: string): Promise<ConversationSummary[]> {
  if (sql) {
    await initializeRemoteDatabase();
    const rows = await sql`
      SELECT c.id, c.title, c.created_at AS "createdAt", c.updated_at AS "updatedAt",
        COUNT(m.id) AS "messageCount"
      FROM conversations c LEFT JOIN messages m ON m.conversation_id = c.id
      WHERE c.owner_id = ${ownerId}
      GROUP BY c.id ORDER BY c.updated_at DESC LIMIT 50
    `;
    return rows.map((row) => ({
      id: String(row.id),
      title: String(row.title),
      createdAt: isoDate(row.createdAt),
      updatedAt: isoDate(row.updatedAt),
      messageCount: Number(row.messageCount)
    }));
  }
  const rows = localDatabase().prepare(`
    SELECT c.id, c.title, c.created_at AS createdAt, c.updated_at AS updatedAt,
      COUNT(m.id) AS messageCount
    FROM conversations c LEFT JOIN messages m ON m.conversation_id = c.id
    WHERE c.owner_id = ?
    GROUP BY c.id ORDER BY c.updated_at DESC LIMIT 50
  `).all(ownerId);
  return rows.map((row) => ({
    id: String(row.id),
    title: String(row.title),
    createdAt: String(row.createdAt),
    updatedAt: String(row.updatedAt),
    messageCount: Number(row.messageCount)
  }));
}

export async function getConversation(id: string, ownerId: string) {
  if (sql) {
    await initializeRemoteDatabase();
    const [row] = await sql`
      SELECT id, title, created_at AS "createdAt", updated_at AS "updatedAt"
      FROM conversations WHERE id = ${id} AND owner_id = ${ownerId}
    `;
    if (!row) return null;
    const messageRows = await sql`
      SELECT id, role, content, agent, created_at AS "createdAt"
      FROM messages WHERE conversation_id = ${id} ORDER BY id
    `;
    const messages: ConversationMessage[] = messageRows.map((message) => ({
      id: Number(message.id),
      role: String(message.role) as ConversationMessage["role"],
      content: String(message.content),
      agent: message.agent === null ? null : String(message.agent),
      createdAt: isoDate(message.createdAt)
    }));
    return {
      id: String(row.id),
      title: String(row.title),
      createdAt: isoDate(row.createdAt),
      updatedAt: isoDate(row.updatedAt),
      messages
    };
  }
  const row = localDatabase().prepare(`
    SELECT id, title, created_at AS createdAt, updated_at AS updatedAt
    FROM conversations WHERE id = ? AND owner_id = ?
  `).get(id, ownerId);
  if (!row) return null;

  const messageRows = localDatabase().prepare(`
    SELECT id, role, content, agent, created_at AS createdAt
    FROM messages WHERE conversation_id = ? ORDER BY id
  `).all(id);
  const messages: ConversationMessage[] = messageRows.map((message) => ({
    id: Number(message.id),
    role: String(message.role) as ConversationMessage["role"],
    content: String(message.content),
    agent: message.agent === null ? null : String(message.agent),
    createdAt: String(message.createdAt)
  }));
  return {
    id: String(row.id),
    title: String(row.title),
    createdAt: String(row.createdAt),
    updatedAt: String(row.updatedAt),
    messages
  };
}

export async function createConversation(title: string, ownerId: string) {
  const id = crypto.randomUUID();
  const now = new Date().toISOString();
  if (sql) {
    await initializeRemoteDatabase();
    await sql`INSERT INTO conversations (id, owner_id, title, created_at, updated_at)
      VALUES (${id}, ${ownerId}, ${title}, ${now}, ${now})`;
    return id;
  }
  localDatabase().prepare("INSERT INTO conversations (id, owner_id, title, created_at, updated_at) VALUES (?, ?, ?, ?, ?)")
    .run(id, ownerId, title, now, now);
  return id;
}

export async function addMessage(conversationId: string, role: "user" | "assistant", content: string, agent: string | null = null) {
  const now = new Date().toISOString();
  if (sql) {
    await initializeRemoteDatabase();
    await sql`INSERT INTO messages (conversation_id, role, content, agent, created_at)
      VALUES (${conversationId}, ${role}, ${content}, ${agent}, ${now})`;
    await sql`UPDATE conversations SET updated_at = ${now} WHERE id = ${conversationId}`;
    return;
  }
  localDatabase().prepare("INSERT INTO messages (conversation_id, role, content, agent, created_at) VALUES (?, ?, ?, ?, ?)")
    .run(conversationId, role, content, agent, now);
  localDatabase().prepare("UPDATE conversations SET updated_at = ? WHERE id = ?").run(now, conversationId);
}

export async function deleteConversation(id: string, ownerId: string) {
  if (sql) {
    await initializeRemoteDatabase();
    const rows = await sql`DELETE FROM conversations WHERE id = ${id} AND owner_id = ${ownerId} RETURNING id`;
    return rows.length > 0;
  }
  return localDatabase().prepare("DELETE FROM conversations WHERE id = ? AND owner_id = ?").run(id, ownerId).changes > 0;
}
